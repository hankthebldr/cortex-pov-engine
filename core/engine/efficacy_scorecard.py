def render_markdown(scorecard: EfficacyScorecard) -> str:
    """Render the scorecard as Cortex-branded markdown for report export."""
    sc = scorecard
    cov = sc.coverage
    lines: list[str] = []

    lines.append(f"# {sc.title}")
    lines.append("")
    lines.append("---")
    lines.append("")
    scope = (f"{sc.run_count} run(s)" if sc.run_count != 1 else "1 run")
    lines.append(f"**Scope:** {scope}  ")
    if sc.run_ids:
        lines.append(f"**Runs:** {', '.join(f'`{r}`' for r in sc.run_ids)}  ")
    lines.append(f"**Generated:** {sc.generated_at}  ")
    lines.append("")

    # Executive summary
    lines.append("## Executive Summary")
    lines.append("")
    lines.append(
        f"Cortex detected **{cov.detected} of {cov.expected}** expected "
        f"detections (**{cov.pct}% coverage**) across {scope}. "
        f"{_verdict(cov.pct)}"
    )
    lines.append("")

    # Test-case verdict. Deliberately its own section directly under the
    # summary: coverage is "how much of what we expected did we see", the
    # verdict is "did the test case meet its bar", and a reader who sees only
    # the first will take a high coverage number as a pass.
    v = sc.verdicts
    if v.passed or v.failed or v.pending or v.not_applicable or v.unscored:
        lines.append("## Test-Case Verdict")
        lines.append("")
        if v.scored:
            lines.append(
                f"**{v.passed} of {v.scored}** scoreable test case(s) met their "
                f"threshold (**{v.pass_pct}%**)."
            )
        else:
            lines.append(
                "No test case in this scope carries a machine-evaluable "
                "threshold, so none can be certified as passed."
            )
        if v.not_applicable:
            lines.append("")
            lines.append(
                f"_{v.not_applicable} test case(s) report `not_applicable` — the "
                f"index defines no measurable threshold for them, so a pass "
                f"cannot be asserted._"
            )
        if v.pending:
            lines.append("")
            lines.append(f"_{v.pending} still pending verification._")
        lines.append("")

    # Coverage headline
    lines.append("## Detection Coverage")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|--------|-------|")
    lines.append(f"| Coverage | **{cov.pct}%** |")
    lines.append(f"| Detected | {cov.detected} |")
    lines.append(f"| Missed | {cov.missed} |")
    lines.append(f"| Pending | {cov.pending} |")
    lines.append(f"| Expected (denominator) | {cov.expected} |")
    lines.append("")

    # MTTD
    lines.append("## Mean Time to Detect (MTTD)")
    lines.append("")
    if sc.mttd.count:
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| Fastest (min) | {format_mttd(sc.mttd.min_seconds)} |")
        lines.append(f"| Median (p50) | **{format_mttd(sc.mttd.median_seconds)}** |")
        lines.append(f"| p90 | {format_mttd(sc.mttd.p90_seconds)} |")
        lines.append(f"| Slowest (max) | {format_mttd(sc.mttd.max_seconds)} |")
        lines.append(f"| Detections measured | {sc.mttd.count} |")
    else:
        lines.append("_No evidence-backed MTTD measured for this scope._")
    lines.append("")

    def _bd_table(header: str, rows: Iterable[BreakdownRow]) -> None:
        rows = list(rows)
        if not rows:
            return
        lines.append(f"## Coverage by {header}")
        lines.append("")
        lines.append(f"| {header} | Coverage | Detected | Missed | Pending | Expected |")
        lines.append("|" + "---|" * 6)
        for r in rows:
            lines.append(
                f"| {r.label} | {r.pct}% | {r.detected} | {r.missed} | "
                f"{r.pending} | {r.expected} |"
            )
        lines.append("")

    _bd_table("Cortex Product", sc.by_product)
    _bd_table("Detection Plane", sc.by_plane)
    _bd_table("Detection Type", sc.by_detection_type)

    lines.append("---")
    lines.append("")
    lines.append("*Generated by CortexSim — Palo Alto Networks Cortex Detection "
                 "Simulation Engine*")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# HTML renderer (Cortex-branded, self-contained)
# ---------------------------------------------------------------------------


def _pct_bar(pct: float) -> str:
    return (
        f'<div class="cs-bar"><div class="cs-bar-fill" '
        f'style="width:{max(0.0, min(100.0, pct))}%"></div></div>'
    )


def _bd_html(header: str, rows: Iterable[BreakdownRow]) -> str:
    rows = list(rows)
    if not rows:
        return ""
    body = []
    for r in rows:
        body.append(
            "<tr>"
            f"<td class=\"cs-label\">{html.escape(r.label)}</td>"
            f"<td class=\"cs-pct\">{r.pct}% {_pct_bar(r.pct)}</td>"
            f"<td class=\"cs-num cs-det\">{r.detected}</td>"
            f"<td class=\"cs-num cs-miss\">{r.missed}</td>"
            f"<td class=\"cs-num cs-pend\">{r.pending}</td>"
            f"<td class=\"cs-num\">{r.expected}</td>"
            "</tr>"
        )
    return (
        f'<section class="cs-section"><h2>Coverage by {html.escape(header)}</h2>'
        '<table class="cs-table"><thead><tr>'
        f"<th>{html.escape(header)}</th><th>Coverage</th><th>Detected</th>"
        "<th>Missed</th><th>Pending</th><th>Expected</th>"
        "</tr></thead><tbody>" + "".join(body) + "</tbody></table></section>"
    )


def render_html(scorecard: EfficacyScorecard) -> str:
    """Render the scorecard as a self-contained Cortex-branded HTML document."""
    sc = scorecard
    cov = sc.coverage
    scope = (f"{sc.run_count} runs" if sc.run_count != 1 else "1 run")

    def _kpi(value: str, label: str, accent: str = _CORTEX_TEAL) -> str:
        return (
            f'<div class="cs-kpi"><div class="cs-kpi-val" style="color:{accent}">'
            f'{html.escape(value)}</div>'
            f'<div class="cs-kpi-lbl">{html.escape(label)}</div></div>'
        )

    mttd_kpis = ""
    if sc.mttd.count:
        mttd_kpis = (
            _kpi(format_mttd(sc.mttd.median_seconds), "Median MTTD (p50)")
            + _kpi(format_mttd(sc.mttd.p90_seconds), "p90 MTTD", _CORTEX_STEEL)
        )

    style = f"""
    .cs-root {{ font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI',
        sans-serif; color: {_CORTEX_NAVY}; max-width: 960px; margin: 0 auto;
        padding: 32px; background: #fff; }}
    .cs-root h1 {{ font-size: 26px; margin: 0 0 4px; color: {_CORTEX_NAVY}; }}
    .cs-root h2 {{ font-size: 18px; margin: 28px 0 12px; color: {_CORTEX_NAVY};
        border-bottom: 2px solid {_CORTEX_TEAL}; padding-bottom: 4px; }}
    .cs-meta {{ color: {_CORTEX_STEEL}; font-size: 13px; margin-bottom: 20px; }}
    .cs-meta code {{ font-family: 'JetBrains Mono', monospace; font-size: 12px; }}
    .cs-summary {{ background: {_CORTEX_NAVY}; color: #fff; padding: 20px 24px;
        border-radius: 8px; line-height: 1.5; }}
    .cs-summary strong {{ color: {_CORTEX_TEAL}; }}
    .cs-kpis {{ display: flex; flex-wrap: wrap; gap: 16px; margin: 20px 0; }}
    .cs-kpi {{ flex: 1 1 140px; border: 1px solid #e2e8ee; border-radius: 8px;
        padding: 16px; text-align: center; }}
    .cs-kpi-val {{ font-size: 30px; font-weight: 700; font-family: 'JetBrains Mono',
        monospace; }}
    .cs-kpi-lbl {{ font-size: 12px; color: {_CORTEX_STEEL}; margin-top: 4px;
        text-transform: uppercase; letter-spacing: .04em; }}
    .cs-table {{ width: 100%; border-collapse: collapse; font-size: 14px; }}
    .cs-table th {{ text-align: left; color: {_CORTEX_STEEL}; font-weight: 600;
        border-bottom: 2px solid #e2e8ee; padding: 8px 10px; }}
    .cs-table td {{ border-bottom: 1px solid #eef2f6; padding: 8px 10px; }}
    .cs-num {{ text-align: right; font-family: 'JetBrains Mono', monospace; }}
    .cs-det {{ color: {_DETECTED_GREEN}; font-weight: 600; }}
    .cs-miss {{ color: {_MISSED_RED}; }}
    .cs-pend {{ color: {_PENDING_AMBER}; }}
    .cs-pct {{ white-space: nowrap; }}
    .cs-bar {{ display: inline-block; width: 90px; height: 8px; background: #e2e8ee;
        border-radius: 4px; overflow: hidden; vertical-align: middle;
        margin-left: 8px; }}
    .cs-bar-fill {{ height: 100%; background: {_CORTEX_TEAL}; }}
    .cs-foot {{ margin-top: 32px; color: {_CORTEX_STEEL}; font-size: 12px;
        border-top: 1px solid #e2e8ee; padding-top: 12px; }}
    """

    run_ids_html = ""
    if sc.run_ids:
        run_ids_html = ("<div class=\"cs-meta\">Runs: "
                        + ", ".join(f"<code>{html.escape(r)}</code>" for r in sc.run_ids)
                        + "</div>")

    accent = (_DETECTED_GREEN if cov.pct >= 80
              else _CORTEX_TEAL if cov.pct >= 50 else _MISSED_RED)

    doc = (
        f"<style>{style}</style>"
        '<div class="cs-root">'
        f"<h1>{html.escape(sc.title)}</h1>"
        f'<div class="cs-meta">Scope: {html.escape(scope)} · '
        f"Generated {html.escape(sc.generated_at)}</div>"
        f"{run_ids_html}"
        f'<div class="cs-summary">Cortex detected '
        f"<strong>{cov.detected} of {cov.expected}</strong> expected detections "
        f"(<strong>{cov.pct}% coverage</strong>) across {html.escape(scope)}. "
        f"{html.escape(_verdict(cov.pct))}</div>"
        '<div class="cs-kpis">'
        + _kpi(f"{cov.pct}%", "Coverage", accent)
        + _kpi(str(cov.detected), "Detected", _DETECTED_GREEN)
        + _kpi(str(cov.missed), "Missed", _MISSED_RED)
        + _kpi(str(cov.pending), "Pending", _PENDING_AMBER)
        + mttd_kpis
        + "</div>"
        + _bd_html("Cortex Product", sc.by_product)
        + _bd_html("Detection Plane", sc.by_plane)
        + _bd_html("Detection Type", sc.by_detection_type)
        + '<div class="cs-foot">Generated by CortexSim — Palo Alto Networks '
          "Cortex Detection Simulation Engine</div>"
        "</div>"
    )
    return doc
