def normalize_detection_type(result: dict[str, Any]) -> str:
    """Map a result row onto the six-value detection_type vocabulary.

    Prefers the finer-grained ``detection_kind`` (``bioc | xql | correlation |
    ioc``, populated from the TTP card) and falls back to ``signal_type``
    (``BIOC | IOC | Analytics`` legacy). Anything unrecognized lands in
    ``Other`` so the scorecard never drops a signal.
    """
    kind = (result.get("detection_kind") or "").strip().lower()
    signal = (result.get("signal_type") or "").strip()
    raw = kind or signal.lower()
    mapping = {
        "bioc": "BIOC",
        "abioc": "ABIOC",
        "xql": "XQL",
        "analytics": "Analytics",
        "correlation": "Correlation",
        "ioc": "IOC",
        "prevention": "Prevention",
    }
    if raw in mapping:
        return mapping[raw]
    # signal_type may already be canonical-cased (e.g. "Analytics").
    for dt in DETECTION_TYPES:
        if signal.lower() == dt.lower():
            return dt
    return "Other"


def product_for_plane(plane: Optional[str]) -> str:
    return PLANE_TO_PRODUCT.get((plane or "").strip().lower(), _DEFAULT_PRODUCT)


#: Statuses a scorecard row can take. ``detected_not_prevented`` is a block-mode
#: ``prevent`` expectation the agent only detected: Cortex saw it (a coverage
#: hit) but it is a prevention FAIL, so it never reads as plain "detected".
STATUS_DETECTED_NOT_PREVENTED = "detected_not_prevented"


def _status(result: dict[str, Any]) -> str:
    """The row's status, from ``outcome`` when the engine decided one.

    The one rule, ``engine.outcome.row_status``: an outcome-less row is
    ``detected`` when validated, else ``pending`` (awaiting reconcile) -- never
    ``missed``. An unrecognised outcome raises: it must never read as benign.
    """
    status = row_status(result.get("outcome"), bool(result.get("observed")))
    if status == "detected" and result.get("outcome_reason") == DETECTED_NOT_PREVENTED:
        return STATUS_DETECTED_NOT_PREVENTED
    return status


def _exclusion(result: dict[str, Any]) -> Optional[str]:
    """Why a row leaves the denominator (the one rule), or None when it counts."""
    return denominator_exclusion(SimpleNamespace(
        outcome=result.get("outcome"), outcome_reason=result.get("outcome_reason")))


def _percentile(values: list[float], pct: float) -> Optional[float]:
    """Linear-interpolation percentile (pct in 0..100). Pure, no numpy."""
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return round(ordered[0], 1)
    rank = (pct / 100.0) * (len(ordered) - 1)
    low = int(rank)
    high = min(low + 1, len(ordered) - 1)
    frac = rank - low
    return round(ordered[low] + (ordered[high] - ordered[low]) * frac, 1)


_COUNTED = ("detected", "prevented", STATUS_DETECTED_NOT_PREVENTED, "missed", "pending")


def _tally(rows: Iterable[dict[str, Any]]) -> tuple[dict[str, int], dict[str, int]]:
    """``(counts by status over the denominator, excluded counts by reason)``."""
    counts = {k: 0 for k in _COUNTED}
    excluded = empty_exclusions()
    for r in rows:
        why = _exclusion(r)
        if why is not None:
            excluded[why] += 1
            continue
        counts[_status(r)] += 1
    return counts, excluded


def _coverage_from_tally(counts: dict[str, int],
                         excluded: Optional[dict[str, int]] = None) -> CoverageStats:
    expected = sum(counts.values())
    hits = counts["detected"] + counts["prevented"] + counts[STATUS_DETECTED_NOT_PREVENTED]
    pct = round(hits / expected * 100, 1) if expected else 0.0
    return CoverageStats(
        detected=counts["detected"], missed=counts["missed"], pending=counts["pending"],
        expected=expected, pct=pct, prevented=counts["prevented"],
        detected_not_prevented=counts[STATUS_DETECTED_NOT_PREVENTED],
        excluded=dict(excluded) if excluded is not None else empty_exclusions())


def _breakdown(results: list[dict[str, Any]], key_fn) -> list[BreakdownRow]:
    buckets: dict[str, list[dict[str, Any]]] = {}
    for r in results:
        if _exclusion(r) is not None:
            continue  # counted once, at the top, under ``excluded``
        buckets.setdefault(key_fn(r), []).append(r)
    rows: list[BreakdownRow] = []
    for label, members in buckets.items():
        cov = _coverage_from_tally(_tally(members)[0])
        rows.append(BreakdownRow(label=label, detected=cov.detected, missed=cov.missed,
                                 pending=cov.pending, expected=cov.expected, pct=cov.pct,
                                 prevented=cov.prevented,
                                 detected_not_prevented=cov.detected_not_prevented))
    # Highest coverage-gap first (most missed), then by expected volume — the
    # rows a CISO cares about float to the top.
    rows.sort(key=lambda x: (-(x.missed + x.pending), -x.expected, x.label))
    return rows


def build_efficacy_scorecard(
    results: Iterable[dict[str, Any]],
    *,
    run_ids: Optional[Iterable[str]] = None,
    title: Optional[str] = None,
    generated_at: Optional[str] = None,
    tc_verdicts: Optional[Iterable[Optional[str]]] = None,
    integrity: Optional[dict[str, Any]] = None,
) -> EfficacyScorecard:
    """Build the efficacy scorecard from ``Result.to_dict()``-shaped dicts.

    Works for a single run (pass that run's results) or a portfolio (pass the
    concatenated results of many runs and their ``run_ids``). Pure — no ORM,
    no session, fully unit-testable.
    """
    rows = list(results)

    coverage = _coverage_from_tally(*_tally(rows))

    # A step that never ran cannot contribute a detection time.
    mttds = [float(r["mttd_seconds"]) for r in rows
             if r.get("mttd_seconds") is not None and _exclusion(r) is None]
    mttd = MttdDistribution(
        count=len(mttds),
        min_seconds=round(min(mttds), 1) if mttds else None,
        median_seconds=_percentile(mttds, 50),
        p90_seconds=_percentile(mttds, 90),
        max_seconds=round(max(mttds), 1) if mttds else None,
    )

    by_plane = _breakdown(rows, lambda r: r.get("plane") or "—")
    by_detection_type = _breakdown(rows, normalize_detection_type)
    by_product = _breakdown(rows, lambda r: product_for_plane(r.get("plane")))

    ids = tuple(dict.fromkeys(run_ids or []))  # de-dupe, preserve order
    run_count = len(ids) if ids else (1 if rows else 0)

    # Run.tc_verdict is per-RUN, not per-result, so it arrives alongside the
    # rows rather than inside them. A run with no verdict counts as unscored —
    # never silently as a pass.
    counts: dict[str, int] = {}
    for v in (tc_verdicts or []):
        counts[v or "unscored"] = counts.get(v or "unscored", 0) + 1
    tally = VerdictTally(
        passed=counts.get("pass", 0),
        failed=counts.get("fail", 0),
        pending=counts.get("pending", 0),
        not_applicable=counts.get("not_applicable", 0),
        unscored=counts.get("unscored", 0),
    )

    return EfficacyScorecard(
        title=title or "Cortex POV Efficacy Scorecard",
        run_count=run_count,
        run_ids=ids,
        coverage=coverage,
        mttd=mttd,
        by_plane=tuple(by_plane),
        by_detection_type=tuple(by_detection_type),
        by_product=tuple(by_product),
        generated_at=generated_at or datetime.now(timezone.utc).isoformat(),
        verdicts=tally,
        integrity=integrity,
    )


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def format_mttd(seconds: Optional[float]) -> str:
    """Human-readable MTTD. Mirrors runs.py:_fmt_mttd so the two agree."""
    if seconds is None:
        return "—"
    if seconds < 60:
        return f"{seconds:g}s"
    if seconds < 3600:
        return f"{int(seconds // 60)}m {int(seconds % 60)}s"
    return f"{int(seconds // 3600)}h {int((seconds % 3600) // 60)}m"


def _verdict(coverage: CoverageStats) -> str:
    """The exec-summary verdict, degraded-aware.

    ``pct`` is ``detected / expected`` with pending folded into the denominator,
    so a scope where nothing has been adjudicated reads as 0% — and emitting the
    coverage-gap verdict there puts a false-negative claim about the customer's
    stack into a CISO one-pager before anything was measured. A zero is degraded,
    not ok: "none defined" and "none validated yet" get their own verdict, never
    the authored-content recommendation that only an actual miss warrants.
    """
    adjudicated = coverage.hits + coverage.missed
    if coverage.expected == 0:
        return ("No expected detections were defined for this scope, so Cortex "
                "detection coverage cannot be assessed — there was nothing to "
                "detect.")
    if adjudicated == 0:
        return (f"No detections have been validated yet ({coverage.pending} "
                f"pending), so coverage cannot be concluded — the seeded results "
                f"have not been adjudicated against the Cortex console.")
    pct = coverage.pct
    if pct >= 80:
        return ("Strong Cortex detection coverage confirmed across the simulated "
                "surface. Recommend promoting to a customer-facing POV report.")
    if pct >= 50:
        return ("Partial detection coverage. Recommend reviewing the missed "
                "detections and considering custom-rule remediation before hand-off.")
    return ("Coverage gap identified. Recommend authoring BIOC / correlation "
            "content to close the missed-detection delta before hand-off.")


def _excluded_line(excluded: dict[str, int]) -> str:
    """The exclusions, listed the way the run report lists them."""
    parts = ", ".join(f"{k} {v}" for k, v in excluded.items() if v)
    return (f"_Excluded from the denominator: {parts} — a step that never ran, or "
            f"an Analytics/ABIOC detector still in its soak period, is neither a "
            f"hit nor a miss._")


def _is_degraded(coverage: CoverageStats) -> bool:
    """True when nothing in scope was measured (no expected, or all pending)."""
    return coverage.expected == 0 or (coverage.hits + coverage.missed) == 0


