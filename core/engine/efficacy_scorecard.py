"""
core/engine/efficacy_scorecard.py — POV efficacy scorecard.

Computes a Cortex-branded *efficacy scorecard* from one **or many** runs'
``Result`` rows. The scorecard is the CISO/exec one-pager companion to the
per-detection POV report generated by ``core/api/runs.py`` + the artifact set
in ``core/engine/report_generator.py``:

  * overall detection coverage % (detected / expected)
  * detected / missed / pending counts
  * MTTD distribution — min / median / p90 / max
  * coverage broken down **by plane**, **by detection_type**
    (``BIOC | XQL | Analytics | Correlation | IOC | ABIOC``), and **by Cortex
    product** (EDR → Cortex XDR, CDR → Cortex Cloud, …)

Design mirrors ``report_generator.py`` exactly:

  * **pure** — consumes only ``Result.to_dict()``-shaped dicts (the shape
    already emitted by ``core/models.py``); imports no ORM/session/FastAPI.
  * **frozen dataclasses** with ``.to_dict()`` so the API layer can serialize.
  * status derivation matches ``report_generator._status_from_result`` so the
    scorecard and the detection matrix never disagree.

Bolts onto the existing report export via a ``?format=scorecard`` branch on
``GET /api/runs/{id}/report`` (see the integration patch in the handoff).
"""

from __future__ import annotations

import dataclasses
import html
import logging
from datetime import datetime, timezone
from typing import Any, Iterable, Optional


logger = logging.getLogger("cortexsim.engine.efficacy_scorecard")


# ---------------------------------------------------------------------------
# Cortex vocabulary + product mapping
# ---------------------------------------------------------------------------

# The full six-value detection_type vocabulary. Anything that does not
# normalize into one of these buckets is surfaced under ``Other`` so the
# scorecard never silently drops a signal type.
DETECTION_TYPES: tuple[str, ...] = (
    "BIOC", "XQL", "Analytics", "Correlation", "IOC", "ABIOC",
)

# Plane → customer-facing Cortex product. Lower-cased plane keys (planes ship
# as lower-case module names — ``edr``, ``cdr``, …) so lookups are
# case-insensitive. Unmapped planes fall back to ``Cortex XSIAM`` (the SIEM
# substrate every plane ultimately lands in).
PLANE_TO_PRODUCT: dict[str, str] = {
    "edr": "Cortex XDR",
    "koi": "Cortex XDR",
    "cdr": "Cortex Cloud",
    "cspm": "Cortex Cloud",
    "cloud_app": "Cortex Cloud",
    "ndr": "Cortex XSIAM",
    "itdr": "Cortex XSIAM",
    "analytics": "Cortex XSIAM",
    "tim": "Cortex XSIAM",
    "email": "Cortex XSIAM",
    "asm": "Cortex ASM",
    "airs": "Cortex AIRS",
    "ai_access": "Cortex AI Access Security",
    "ai_spm": "Cortex AI-SPM",
    "browser": "Prisma Browser",
}
_DEFAULT_PRODUCT = "Cortex XSIAM"

# Cortex design tokens (mirrors ui/src/styles/cortex-theme.css).
_CORTEX_NAVY = "#003366"
_CORTEX_TEAL = "#00C0E8"
_CORTEX_STEEL = "#6B7E8E"
_DETECTED_GREEN = "#1f9d55"
_MISSED_RED = "#e60d0d"
_PENDING_AMBER = "#c98a00"


# ---------------------------------------------------------------------------
# Dataclasses
# ---------------------------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class CoverageStats:
    detected: int
    missed: int
    pending: int
    expected: int
    pct: float

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


@dataclasses.dataclass(frozen=True)
class MttdDistribution:
    count: int
    min_seconds: Optional[float]
    median_seconds: Optional[float]
    p90_seconds: Optional[float]
    max_seconds: Optional[float]

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


@dataclasses.dataclass(frozen=True)
class BreakdownRow:
    """One coverage row for a plane / detection_type / product breakdown."""

    label: str
    detected: int
    missed: int
    pending: int
    expected: int
    pct: float

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


@dataclasses.dataclass(frozen=True)
class VerdictTally:
    """How many runs actually MET their bound test case's bar.

    Coverage answers "how much of what we expected did we see". It does not
    answer "did the test case pass", which is the question a POV readout turns
    on — and the two diverge: a run can observe every seeded detection and still
    miss its MTTD threshold. ``not_applicable`` is carried explicitly rather
    than folded into a pass rate, because a test case the index gave no
    measurable threshold can never be certified and saying so is the point.
    """

    passed: int = 0
    failed: int = 0
    pending: int = 0
    not_applicable: int = 0
    unscored: int = 0            # no verdict recorded at all

    @property
    def scored(self) -> int:
        return self.passed + self.failed

    @property
    def pass_pct(self) -> Optional[float]:
        """Share of SCOREABLE runs that passed. None when nothing was scoreable
        — a 0% that really means "nothing could be scored" misleads a reader."""
        return round(self.passed / self.scored * 100, 1) if self.scored else None

    def to_dict(self) -> dict[str, Any]:
        return {
            "passed": self.passed, "failed": self.failed,
            "pending": self.pending, "not_applicable": self.not_applicable,
            "unscored": self.unscored,
            "scored": self.scored, "pass_pct": self.pass_pct,
        }


@dataclasses.dataclass(frozen=True)
class EfficacyScorecard:
    title: str
    run_count: int
    run_ids: tuple[str, ...]
    coverage: CoverageStats
    mttd: MttdDistribution
    by_plane: tuple[BreakdownRow, ...]
    by_detection_type: tuple[BreakdownRow, ...]
    by_product: tuple[BreakdownRow, ...]
    generated_at: str
    verdicts: VerdictTally = dataclasses.field(default_factory=VerdictTally)

    def to_dict(self) -> dict[str, Any]:
        return {
            "title": self.title,
            "run_count": self.run_count,
            "run_ids": list(self.run_ids),
            "coverage": self.coverage.to_dict(),
            "verdicts": self.verdicts.to_dict(),
            "mttd": self.mttd.to_dict(),
            "by_plane": [r.to_dict() for r in self.by_plane],
            "by_detection_type": [r.to_dict() for r in self.by_detection_type],
            "by_product": [r.to_dict() for r in self.by_product],
            "generated_at": self.generated_at,
        }


# ---------------------------------------------------------------------------
# Core builder (pure)
# ---------------------------------------------------------------------------


def normalize_detection_type(result: dict[str, Any]) -> str:
    """Map a result row onto the six-value detection_type vocabulary.

    Prefers the finer-grained ``detection_kind`` (``bioc | xql | correlation |
    ioc``, populated from the TTP card) and falls back to ``signal_type``
    (``BIOC | IOC | Analytics`` legacy). Anything unrecognized lands in
    ``Other`` so the scorecard never drops a signal.
    """
    kind = (result.get("detection_kind") or "").strip().lower()
    signal = (result.get("signal_type") or "").strip()
    raw = kind or signal.lower()
    mapping = {
        "bioc": "BIOC",
        "abioc": "ABIOC",
        "xql": "XQL",
        "analytics": "Analytics",
        "correlation": "Correlation",
        "ioc": "IOC",
    }
    if raw in mapping:
        return mapping[raw]
    # signal_type may already be canonical-cased (e.g. "Analytics").
    for dt in DETECTION_TYPES:
        if signal.lower() == dt.lower():
            return dt
    return "Other"


def product_for_plane(plane: Optional[str]) -> str:
    return PLANE_TO_PRODUCT.get((plane or "").strip().lower(), _DEFAULT_PRODUCT)


def _status(result: dict[str, Any]) -> str:
    """detected | missed | pending — matches report_generator._status_from_result."""
    if result.get("observed"):
        return "detected"
    if result.get("observed_at"):
        return "missed"
    return "pending"


def _percentile(values: list[float], pct: float) -> Optional[float]:
    """Linear-interpolation percentile (pct in 0..100). Pure, no numpy."""
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return round(ordered[0], 1)
    rank = (pct / 100.0) * (len(ordered) - 1)
    low = int(rank)
    high = min(low + 1, len(ordered) - 1)
    frac = rank - low
    return round(ordered[low] + (ordered[high] - ordered[low]) * frac, 1)


def _coverage_from_counts(detected: int, missed: int, pending: int) -> CoverageStats:
    expected = detected + missed + pending
    pct = round(detected / expected * 100, 1) if expected else 0.0
    return CoverageStats(detected=detected, missed=missed, pending=pending,
                         expected=expected, pct=pct)


def _breakdown(results: list[dict[str, Any]], key_fn) -> list[BreakdownRow]:
    buckets: dict[str, dict[str, int]] = {}
    for r in results:
        label = key_fn(r)
        slot = buckets.setdefault(label, {"detected": 0, "missed": 0, "pending": 0})
        slot[_status(r)] += 1
    rows: list[BreakdownRow] = []
    for label, slot in buckets.items():
        cov = _coverage_from_counts(slot["detected"], slot["missed"], slot["pending"])
        rows.append(BreakdownRow(label=label, detected=cov.detected, missed=cov.missed,
                                 pending=cov.pending, expected=cov.expected, pct=cov.pct))
    # Highest coverage-gap first (most missed), then by expected volume — the
    # rows a CISO cares about float to the top.
    rows.sort(key=lambda x: (-(x.missed + x.pending), -x.expected, x.label))
    return rows


def build_efficacy_scorecard(
    results: Iterable[dict[str, Any]],
    *,
    run_ids: Optional[Iterable[str]] = None,
    title: Optional[str] = None,
    generated_at: Optional[str] = None,
    tc_verdicts: Optional[Iterable[Optional[str]]] = None,
) -> EfficacyScorecard:
    """Build the efficacy scorecard from ``Result.to_dict()``-shaped dicts.

    Works for a single run (pass that run's results) or a portfolio (pass the
    concatenated results of many runs and their ``run_ids``). Pure — no ORM,
    no session, fully unit-testable.
    """
    rows = list(results)

    detected = sum(1 for r in rows if _status(r) == "detected")
    missed = sum(1 for r in rows if _status(r) == "missed")
    pending = sum(1 for r in rows if _status(r) == "pending")
    coverage = _coverage_from_counts(detected, missed, pending)

    mttds = [float(r["mttd_seconds"]) for r in rows if r.get("mttd_seconds") is not None]
    mttd = MttdDistribution(
        count=len(mttds),
        min_seconds=round(min(mttds), 1) if mttds else None,
        median_seconds=_percentile(mttds, 50),
        p90_seconds=_percentile(mttds, 90),
        max_seconds=round(max(mttds), 1) if mttds else None,
    )

    by_plane = _breakdown(rows, lambda r: r.get("plane") or "—")
    by_detection_type = _breakdown(rows, normalize_detection_type)
    by_product = _breakdown(rows, lambda r: product_for_plane(r.get("plane")))

    ids = tuple(dict.fromkeys(run_ids or []))  # de-dupe, preserve order
    run_count = len(ids) if ids else (1 if rows else 0)

    # Run.tc_verdict is per-RUN, not per-result, so it arrives alongside the
    # rows rather than inside them. A run with no verdict counts as unscored —
    # never silently as a pass.
    counts: dict[str, int] = {}
    for v in (tc_verdicts or []):
        counts[v or "unscored"] = counts.get(v or "unscored", 0) + 1
    tally = VerdictTally(
        passed=counts.get("pass", 0),
        failed=counts.get("fail", 0),
        pending=counts.get("pending", 0),
        not_applicable=counts.get("not_applicable", 0),
        unscored=counts.get("unscored", 0),
    )

    return EfficacyScorecard(
        title=title or "Cortex POV Efficacy Scorecard",
        run_count=run_count,
        run_ids=ids,
        coverage=coverage,
        mttd=mttd,
        by_plane=tuple(by_plane),
        by_detection_type=tuple(by_detection_type),
        by_product=tuple(by_product),
        generated_at=generated_at or datetime.now(timezone.utc).isoformat(),
        verdicts=tally,
    )


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def format_mttd(seconds: Optional[float]) -> str:
    """Human-readable MTTD. Mirrors runs.py:_fmt_mttd so the two agree."""
    if seconds is None:
        return "—"
    if seconds < 60:
        return f"{seconds:g}s"
    if seconds < 3600:
        return f"{int(seconds // 60)}m {int(seconds % 60)}s"
    return f"{int(seconds // 3600)}h {int((seconds % 3600) // 60)}m"


def _verdict(pct: float) -> str:
    if pct >= 80:
        return ("Strong Cortex detection coverage confirmed across the simulated "
                "surface. Recommend promoting to a customer-facing POV report.")
    if pct >= 50:
        return ("Partial detection coverage. Recommend reviewing the missed "
                "detections and considering custom-rule remediation before hand-off.")
    return ("Coverage gap identified. Recommend authoring BIOC / correlation "
            "content to close the missed-detection delta before hand-off.")


